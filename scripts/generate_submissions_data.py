#!/usr/bin/env python3
"""Regenerate submissions-data.js for the gallery pages (organiser step, after review).

    python scripts/generate_submissions_data.py

Lists every package under submissions/ with its gate result and fingerprint. An entry is shown as
published only if gallery/gallery-publication.json records it with the sha256 of the reviewed version
and that sha256 still matches the package: merge is not publication.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import xcity_common as xc  # noqa: E402


def cover(pkg, m):
    """The picture for the gallery card: the city seen whole if there is one, else a node aerial, else the structure."""
    reg = {i.get("path") for i in (xc.load_json(os.path.join(pkg, "image_provenance.json")).get("images", [])
                                   if os.path.exists(os.path.join(pkg, "image_provenance.json")) else [])}
    b = m.get("booklet") if isinstance(m.get("booklet"), dict) else {}
    tries = [b["cover"]] if b.get("cover") else []
    tries += [r for r in ("media/city-aerial.jpg", "media/city-aerial.png") if r in reg]
    tries += ["renders/city-aerial.png"]
    tries += ["figures/node-%s-aerial.png" % n for n in m.get("nodes", [])[:1]] + ["figures/fig-01-structure.png"]
    for rel in tries:
        if os.path.exists(os.path.join(pkg, rel)):
            return rel
    return ""


def main():
    base = os.path.join(xc.ROOT, "submissions")
    pubf = os.path.join(xc.ROOT, "gallery", "gallery-publication.json")
    pub = {p["path"]: p for p in (xc.load_json(pubf).get("published", []) if os.path.exists(pubf) else [])}
    rows = []
    catalogue = {n["id"]: n for n in xc.load_json(os.path.join(xc.ROOT,"brief/site-package/nodes/design_nodes.json"))["nodes"]}
    statuses = {x["path"]: x for x in xc.load_json(os.path.join(xc.ROOT,"gallery/example-status.json")).get("examples",[])}
    for login in sorted(os.listdir(base)) if os.path.isdir(base) else []:
        d = os.path.join(base, login)
        if not os.path.isdir(d):
            continue
        for slug in sorted(os.listdir(d)):
            pkg = os.path.join(d, slug)
            mp = os.path.join(pkg, "manifest.json")
            if not os.path.isfile(mp):
                continue
            m = xc.load_json(mp)
            scp = os.path.join(pkg, "self_check.json")
            sc = xc.load_json(scp) if os.path.exists(scp) else {}
            path = "submissions/%s/%s" % (login, slug)
            sha = xc.package_sha256(pkg)
            p = pub.get(path)
            rows.append({
                "login": login, "slug": slug, "path": path,
                "title": m.get("title", slug), "title_zh": "", "summary": m.get("summary", ""),
                "language": m.get("language", ""), "agent": (m.get("agent") or {}).get("name", ""),
                "model": (m.get("agent") or {}).get("model", ""),
                "autonomy": (m.get("autonomy") or {}).get("class", ""),
                "automatic_compliance_note": "Gate results are not design approval; design content review is recorded separately.",
                "state": m.get("package_state", "draft"), "nodes": sorted(m.get("nodes", [])),
                "node_labels": [{"id": n, "en": catalogue[n]["en"], "zh": catalogue[n]["zh"]} for n in sorted(m.get("nodes", []))],
                "example_status": statuses.get(path,{}).get("status"),
                "gates_total": sc.get("gates_total", 12), "gates_passed": sc.get("gates_passed", 0),
                "gates_pass": bool(sc.get("pass")),
                "design_content_review_status": p.get("design_content_review", "not_assessed") if p and p.get("reviewed_package_sha256") == sha else "not_recorded_for_current_version", "package_sha256": sha,
                "reviewed_package_sha256": p.get("reviewed_package_sha256") if p else None,
                "published": bool(p and p.get("reviewed_package_sha256") == sha),
                "featured": bool(p and p.get("featured")),
                "example": login == "EXAMPLE-agent",
                "cover": cover(pkg, m), "cover_fit": (m.get("booklet") or {}).get("cover_fit", "cover"),
                "thesis": m.get("thesis", ""),
                "files": [[f, os.path.getsize(os.path.join(pkg, f))] for f in xc.package_files(pkg)],
            })
    js = "// generated by scripts/generate_submissions_data.py - do not edit\nwindow.XCITY_SUBMISSIONS = %s;\n" % \
        json.dumps(rows, ensure_ascii=False, indent=2)
    out = sys.argv[1] if len(sys.argv) > 1 else xc.ROOT   # the gh-pages checkout, where the website lives
    open(os.path.join(out, "submissions-data.js"), "w", encoding="utf-8").write(js)
    print("submissions-data.js: %d packages" % len(rows))


if __name__ == "__main__":
    main()
