#!/usr/bin/env python3
"""Refresh only inlined site boundary/terrain clip paths; preserve all page UI.
The original map viewport was generated by build_public.py in the predecessor
repository. Its geographic display transform is retained here (sub-pixel fit to
archived issued coordinates), so systems, roads and interaction positions do not
move. The outline itself always comes from the current authoritative GeoJSON.
"""
from pathlib import Path
import re,json
R=Path(__file__).resolve().parents[1];B=R/'brief/site-package/boundaries'
g=json.loads((B/'scope_9_13.geojson').read_text())['features'][0]['geometry']
revision=json.loads((B/'boundary-revision.json').read_text())['revision']
def point(p):return 676.1498987674877*p[0]+46304.12803309256,-788.2061272689558*p[1]-24059.47807042068
polygons=g['coordinates'] if g['type']=='MultiPolygon' else [g['coordinates']]
newpath=''.join(' '.join(('M' if i==0 else 'L')+f'{point(p)[0]:.3f} {point(p)[1]:.3f}' for i,p in enumerate(ring))+'Z' for poly in polygons for ring in poly)
for name in ['index.html','agent.html','practice.html','brief.html']:
 p=R/name;s=p.read_text();changed=[0]
 def update(m):
  svg=m.group();clip=re.search(r'<clipPath id="siteclip">\s*<path d="([^"]+)"',svg)
  if not clip:return svg
  previous=clip.group(1);count=svg.count('d="'+previous+'"');assert count==2,(name,count)
  svg=svg.replace('d="'+previous+'"','d="'+newpath+'"')
  svg=re.sub(r' data-boundary-revision="[^"]*"','',svg)
  svg=svg.replace('<svg ','<svg data-boundary-revision="'+revision+'" ',1)
  changed[0]+=1;return svg
 result=re.sub(r'<svg\b[^>]*class="smap".*?</svg>',update,s,flags=re.S)
 if changed[0]:p.write_text(result)
 print(name,changed[0],'site SVGs refreshed')
